const path = require('node:path');
const dotenv = require('dotenv');
const { neon } = require('@neondatabase/serverless');

dotenv.config({ path: path.resolve(__dirname, '../.env.local') });
dotenv.config({ path: path.resolve(__dirname, '../.env') });

if (!process.env.DATABASE_URL) {
  throw new Error('DATABASE_URL is required. Connect a Neon database in Vercel or add it to .env.local for local development.');
}

const sql = neon(process.env.DATABASE_URL);
let schemaPromise;

function ensureSchema() {
  if (!schemaPromise) {
    schemaPromise = sql.transaction([
      sql`CREATE TABLE IF NOT EXISTS visitors (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        initials TEXT,
        name TEXT,
        phone TEXT,
        email TEXT,
        type TEXT,
        visit_reason TEXT,
        ministry TEXT,
        notes TEXT,
        date TEXT,
        status TEXT,
        color TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )`,
      sql`CREATE TABLE IF NOT EXISTS follow_ups (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT,
        person TEXT,
        owner TEXT,
        due TEXT,
        priority TEXT,
        status TEXT
      )`,
      sql`CREATE TABLE IF NOT EXISTS staff_users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email TEXT NOT NULL,
        password_hash TEXT NOT NULL,
        role TEXT NOT NULL DEFAULT 'admin' CHECK (role IN ('admin', 'staff')),
        is_initial_admin BOOLEAN NOT NULL DEFAULT false,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      )`,
      sql`CREATE UNIQUE INDEX IF NOT EXISTS staff_users_email_lower
        ON staff_users (lower(email))`,
      sql`CREATE UNIQUE INDEX IF NOT EXISTS one_initial_admin
        ON staff_users (is_initial_admin) WHERE is_initial_admin = true`,
      sql`CREATE TABLE IF NOT EXISTS web_sessions (
        sid TEXT PRIMARY KEY,
        sess JSONB NOT NULL,
        expires TIMESTAMPTZ NOT NULL
      )`,
    ]).catch((error) => {
      schemaPromise = undefined;
      throw error;
    });
  }
  return schemaPromise;
}

module.exports = { sql, ensureSchema };
